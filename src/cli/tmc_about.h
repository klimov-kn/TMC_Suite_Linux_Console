// tmc_about.h — «О программе», язык сообщений и руководство пользователя
// консольных ядер.
//
// Повторяет окно «О программе» Linux-версии 5.0 с интерфейсом
// (TMC_Suite_Qt/src/gui_common/aboutbox.cpp): название и назначение ядра,
// версия пакета, система, автор и его страницы, сайт, руководство
// пользователя. Окон нет — всё печатается в терминал (рамка, цвет, ссылки), а
// руководство (PDF рядом с ядрами) открывается программой просмотра системы или
// выводится текстом.
//
// Язык (русский/английский) — тот же выбор, что «Настройки → Language / Язык»
// версии с интерфейсом: ~/.config/TMC_Suite_Qt/Common.ini, ключ UI/Language.
//
// К расчёту отношения не имеет.

#pragma once

#include <string>

// Выбрать язык сообщений. pszForced — значение ключа --lang (ru, en, system)
// или nullptr. bMayAsk — можно спросить пользователя (справочные команды,
// запущенные из терминала): спрашивается один раз, ответ запоминается.
// Возвращает false, если значение --lang не распознано.
bool TmcInitLanguage( const char *pszForced, bool bMayAsk );

// Язык сообщений: true — русский.
bool TmcRussian( void );

// Каталог, где лежит сама программа (по /proc/self/exe), без завершающего «/».
std::string TmcExeDir( void );

// Полный путь к руководству (TMC_Suite_User_Manual.pdf) или пустая строка.
// Ищется рядом с программой и в ../share/tmc-suite, ../share/doc/tmc-suite, ../doc, ..
std::string TmcFindManual( void );

// «О программе» в stdout.
void TmcPrintAbout( void );

// Открыть руководство: в графическом сеансе — программой просмотра PDF системы
// (xdg-open); в терминале — текстом через pdftotext и программу постраничного
// просмотра; иначе — где лежит файл и адрес руководства на сайте.
// Возвращает код завершения процесса.
int TmcOpenManual( void );
